import postcss from 'postcss';
import cssnano from 'cssnano';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const names=['base','components','layout','staff','customer','auth','responsive','accessibility','print'];
const source=names.map(name=>`@layer ${name}{${readFileSync(resolve(root,`public/css/${name}.css`),'utf8')}}`).join('\n');
const result=await postcss([cssnano({preset:['default',{cssDeclarationSorter:false,discardComments:{removeAll:true}}]})]).process(`@layer ${names.join(',')};\n${source}`,{from:undefined,map:false});
writeFileSync(resolve(root,'public/styles.css'),`/* Generated by npm run build:styles; edit public/css/*.css. */\n${result.css}\n`);
console.log(JSON.stringify({ok:true,stylesheets:names.length,bytes:Buffer.byteLength(result.css)}));
